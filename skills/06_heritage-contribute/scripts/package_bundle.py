#!/usr/bin/env python3
"""Stage 06 Contribution Bundle Packaging & Provenance Activity for HeritageGraph pipeline.

Packages validated pipeline outputs into a standardized contribution bundle directory:
  - contribution-graph.nq  : RDF triples in named graph (N-Quads)
  - manifest.json          : PROV-O execution activity + run provenance
  - evidence.json          : Per-fact source spans (page, line, cell)
  - rights.json            : Cultural sensitivity + licensing metadata
  - diff_report.json       : Copy of Stage 05 diff report
  - bundle.json            : Bundle manifest with checksums

Each bundle gets a unique named graph IRI:
  heritageGraph:graph/contribution-<run_id>

Aligns with spec #36, closes #41.
"""
import argparse
import hashlib
import json
import shutil
import sys
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

import rdflib
from rdflib import PROV, RDF, RDFS, URIRef, Literal, XSD, Namespace
from rdflib.graph import Dataset

REPO_ROOT = Path(__file__).resolve().parents[3]
COMMON_DIR = REPO_ROOT / "skills" / "common"
SRC_DIR = REPO_ROOT / "src"

for d in (COMMON_DIR, SRC_DIR):
    if str(d) not in sys.path:
        sys.path.insert(0, str(d))

