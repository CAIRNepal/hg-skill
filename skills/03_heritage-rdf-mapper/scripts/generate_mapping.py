#!/usr/bin/env python3
"""Generate the Stage 3 HeritageGraph mapping from the LinkML schema.

Usage:
  generate_mapping.py [--schema schemas/HeritageGraph.yaml] [--overrides FILE]
                      [--out assets/mappings/heritagegraph.yaml] [--check]

Each Container collection maps to its class_uri and each induced slot to its slot_uri, so an
ontology update needs only `update_ontology.py` + this script (zero drift with Stage 1).
A small hand-written overrides file (heritagegraph.overrides.yaml, next to the output) can
replace or suppress individual slot rules (a null value suppresses) or change a class.
With --check nothing is written: exit 1 if --out is missing or differs from a fresh generation
(a stale mapping).
"""
import argparse
import hashlib
import sys
from pathlib import Path

import yaml
from linkml_runtime.utils.schemaview import SchemaView

REPO_ROOT = Path(__file__).resolve().parents[3]
DEFAULT_SCHEMA = REPO_ROOT / "schemas" / "HeritageGraph.yaml"
MAPPINGS_DIR = Path(__file__).resolve().parent.parent / "assets" / "mappings"
DEFAULT_OUT = MAPPINGS_DIR / "heritagegraph.yaml"

HEADER = (
    "# GENERATED by scripts/generate_mapping.py from schemas/HeritageGraph.yaml.\n"
    "# DO NOT EDIT: change the schema and regenerate, or add exceptions to\n"
    "# heritagegraph.overrides.yaml. See references/mapping-format.md (Container mappings).\n"
)


def compact(sv, iri):
    """Full IRI -> CURIE using the schema prefixes (longest namespace wins)."""
    best = None
    for p in sv.schema.prefixes.values():
        ns = p.prefix_reference
        if iri.startswith(ns) and (best is None or len(ns) > len(best[1])):
            best = (p.prefix_prefix, ns)
    return f"{best[0]}:{iri[len(best[1]):]}" if best else iri


def slot_rule(sv, slot):
    rule = {"p": sv.get_uri(slot, expand=False)}
    classes, enums, types = sv.all_classes(), sv.all_enums(), sv.all_types()
    members = [x.range for x in (slot.any_of or [])]
    rng = slot.range or sv.schema.default_range
    if any(m in classes for m in members) or rng in classes:
        rule["ref"] = True
    elif rng in enums:
        rule["enum"] = sv.get_uri(sv.get_enum(rng), expand=False)
    else:
        uri = sv.get_uri(types[rng], expand=True) if rng in types else None
        dt = compact(sv, uri) if uri else None
        if dt and dt != "xsd:string":
            rule["datatype"] = dt
    return rule


def container_collections(sv):
    """[(collection slot name, range class)] for every multivalued class-ranged Container slot,
    excluding provenance slots the Container inherits from Entity (not collections)."""
    classes = sv.all_classes()
    inherited = {s.name for s in sv.class_induced_slots("Entity")}
    return [(s.name, s.range) for s in sv.class_induced_slots("Container")
            if s.range in classes and s.multivalued and s.name not in inherited]


def apply_overrides(collections, overrides):
    for col, ov in ((overrides or {}).get("collections") or {}).items():
        if col not in collections or not ov:
            continue
        if "class" in ov:
            collections[col]["class"] = ov["class"]
        for name, rule in (ov.get("slots") or {}).items():
            if rule is None:
                collections[col]["slots"].pop(name, None)
            else:
                collections[col]["slots"][name] = rule


def generate(schema_path, overrides_path=None):
    sv = SchemaView(str(schema_path))
    collections = {}
    for col, rng in container_collections(sv):
        collections[col] = {
            "class": sv.get_uri(sv.get_class(rng), expand=False),
            "slots": {s.name: slot_rule(sv, s) for s in sv.class_induced_slots(rng)},
        }
    overrides = None
    if overrides_path and Path(overrides_path).exists():
        overrides = yaml.safe_load(Path(overrides_path).read_text(encoding="utf-8"))
    apply_overrides(collections, overrides)

    prefixes = {p.prefix_prefix: p.prefix_reference for p in sv.schema.prefixes.values()
                if p.prefix_prefix != "linkml"}
    doc = {
        "name": "heritagegraph",
        "generated_from": {
            "schema_version": sv.schema.version,
            "sha256": hashlib.sha256(Path(schema_path).read_bytes()).hexdigest(),
        },
        "prefixes": prefixes,
        "container": {"collections": collections},
    }
    body = yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=120)
    return (HEADER + body).encode("utf-8")


def main():
    ap = argparse.ArgumentParser(description="Generate the HeritageGraph Stage 3 mapping from the LinkML schema.")
    ap.add_argument("--schema", default=str(DEFAULT_SCHEMA))
    ap.add_argument("--overrides", default=None, help="Overrides YAML (default: heritagegraph.overrides.yaml next to --out)")
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--check", action="store_true", help="Exit 1 if --out is missing or stale; write nothing")
    args = ap.parse_args()

    out = Path(args.out)
    overrides = Path(args.overrides) if args.overrides else out.parent / "heritagegraph.overrides.yaml"
    content = generate(args.schema, overrides)

    if args.check:
        if out.exists() and out.read_bytes() == content:
            print(f"{out} is up to date")
            return 0
        print(f"{out} is stale or missing; regenerate with generate_mapping.py", file=sys.stderr)
        return 1

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(content)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
